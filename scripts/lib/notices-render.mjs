/**
 * scripts/lib/notices-render.mjs — v21.30: the words of the licence notices
 *
 * Pure functions of their input: the same lockfile and packages give the same
 * bytes, which is what lets `npm run licenses:check` compare files instead of
 * guessing. The notices are built once as blocks (heading, paragraph, table,
 * list, verbatim text) and printed twice — Markdown for the repo, plain text
 * for /licenses/third-party.txt — so the two can never say different things.
 */
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const id = (r) => `${r.name} ${r.version}`;
const shown = (licence) => licence || "(none declared)";

/** Line endings, BOM and trailing spaces are not part of a licence. */
export const tidy = (t) => String(t).replace(/^﻿/, "").replace(/\r\n?/g, "\n")
  .split("\n").map((l) => l.trimEnd()).join("\n").trim();

/** Each distinct licence text once, with every package that ships it, ordered by licence then package. */
export function groupTexts(rows) {
  const byText = new Map();
  for (const r of rows) if (r.texts) (byText.get(r.texts) || byText.set(r.texts, []).get(r.texts)).push(r);
  return [...byText].map(([text, members]) => ({
    text, members, licence: [...new Set(members.map((m) => shown(m.licence)))].sort(cmp).join(", "),
  })).sort((a, b) => cmp(a.licence, b.licence) || cmp(id(a.members[0]), id(b.members[0])));
}

function noticeBlocks(rows, reviewed) {
  const groups = groupTexts(rows);
  const bare = rows.filter((r) => r.texts === "");
  const binaries = rows.filter((r) => r.texts === null);
  const blocks = [
    { h: 1, text: "Third-party notices" },
    { p: `Data Analysis Bot (DAB) is built with the open-source packages listed here: every production dependency of its server (backend/) and its web app (frontend/), ${rows.length} packages in all, with the licence each declares and where its source code lives. The licence texts the packages ship follow, each distinct text printed once with every package that ships it. Development dependencies (build and test tools such as Vite, Tailwind CSS and Supertest) are not listed.` },
    { p: "Fonts: IBM Plex Sans Thai and IBM Plex Mono, © IBM Corp., under the SIL Open Font License 1.1. The full licence is in LICENSES/OFL-1.1-IBM-Plex.txt, served at /licenses/OFL-1.1-IBM-Plex.txt." },
    { p: "Generated by `npm run licenses` from package-lock.json and the installed packages. Do not edit by hand: `npm run licenses:check` fails when this file is stale, or when a package's licence is outside the allow-list and has not been reviewed." },
    { h: 2, text: "Packages" },
    { table: ["Package", "Version", "Licence", "Source"],
      rows: rows.map((r) => [r.name, r.version, shown(r.licence), r.via ? `prebuilt binary for ${r.via}` : r.source || "-"]) },
  ];
  if (reviewed.length) blocks.push(
    { h: 2, text: "Licences reviewed by hand" },
    { p: "These packages declare a licence outside the allow-list (MIT, ISC, BSD-2-Clause, BSD-3-Clause, Apache-2.0, 0BSD, OFL-1.1, CC0-1.0, Unlicense, BlueOak-1.0.0, Python-2.0, CC-BY-4.0, or an OR choice that includes one of them), or none at all. Each was looked at, and the reason it ships is recorded in scripts/third-party-notices.mjs." },
    { list: reviewed.map((r) => `${id(r)} - ${shown(r.licence)}: ${r.note}`) },
  );
  blocks.push({ h: 2, text: "Licence texts" });
  groups.forEach((g, i) => blocks.push(
    { h: 3, text: `${i + 1}. ${g.licence}` },
    { p: `Used by: ${g.members.map(id).join(", ")}` },
    { verbatim: g.text },
  ));
  if (bare.length) blocks.push(
    { h: 3, text: "Packages that ship no licence file" },
    { p: "These packages declare a licence in package.json but include no licence text. The author named in the package is shown." },
    { list: bare.map((r) => [id(r), shown(r.licence), r.author, r.source].filter(Boolean).join(" - ")) },
  );
  if (binaries.length) blocks.push(
    { h: 3, text: "Prebuilt platform binaries" },
    { p: "Each machine installs only the binary for its own system, so these are described from package-lock.json. They ship no licence file; each comes from the same project as the package named." },
    { list: binaries.map((r) => `${id(r)} - ${shown(r.licence)} - prebuilt binary for ${r.via}`) },
  );
  return blocks;
}

// ── Markdown ──────────────────────────────────────────────
const longestRun = (text, ch) => Math.max(0, ...(text.match(new RegExp(`\\${ch}+`, "g")) || []).map((m) => m.length));
const MD = {
  h: (b) => `${"#".repeat(b.h)} ${b.text}`,
  p: (b) => b.p,
  table: (b) => [`| ${b.table.join(" | ")} |`, `|${b.table.map(() => "---").join("|")}|`,
                 ...b.rows.map((r) => `| ${r.map((c) => c.replace(/\|/g, "\\|")).join(" | ")} |`)].join("\n"),
  list: (b) => b.list.map((item) => `- ${item}`).join("\n"),
  verbatim: (b) => { const f = "~".repeat(Math.max(3, longestRun(b.verbatim, "~") + 1)); return `${f}text\n${b.verbatim}\n${f}`; },
};

// ── Plain text ────────────────────────────────────────────
export function wrap(text, width = 78, indent = "", first = indent) {
  const lines = [];
  let line = first, empty = true;   // empty: nothing but the indent yet
  for (const word of String(text).split(/\s+/).filter(Boolean)) {
    if (!empty && line.length + 1 + word.length > width) { lines.push(line); line = indent; empty = true; }
    line += (empty ? "" : " ") + word;
    empty = false;
  }
  return [...lines, line].join("\n");
}
const pad = (cells, widths) => cells.map((c, i) => (i < cells.length - 1 ? c.padEnd(widths[i]) : c)).join("  ");
const TXT = {
  h: (b) => (b.h === 3 ? `== ${b.text} ==` : `${b.text}\n${(b.h === 1 ? "=" : "-").repeat(b.text.length)}`),
  p: (b) => wrap(b.p),
  table: (b) => {
    const all = [b.table, ...b.rows];
    const widths = b.table.map((_, i) => Math.max(...all.map((r) => r[i].length)));
    return [pad(b.table, widths), pad(widths.map((w) => "-".repeat(w)), widths), ...b.rows.map((r) => pad(r, widths))].join("\n");
  },
  list: (b) => b.list.map((item) => wrap(item, 78, "    ", "  - ")).join("\n"),
  verbatim: (b) => b.verbatim,
};

const render = (blocks, fmt) => `${blocks.map((b) => fmt[Object.keys(b).find((k) => k in fmt)](b)).join("\n\n")}\n`;
export const renderMarkdown = (rows, reviewed) => render(noticeBlocks(rows, reviewed), MD);
export const renderText = (rows, reviewed) => render(noticeBlocks(rows, reviewed), TXT);

