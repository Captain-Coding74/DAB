/**
 * The OFL file: a short note from DAB, then IBM's copyright notices and the
 * licence exactly as the font packages ship them. With `derived` (the renamed
 * outlines in tools/hero-bg/assets) the note says they are Modified Versions.
 */
export function renderFontLicence(fonts, derived) {
  const sources = fonts.map((f) => `${f.pkgName} ${f.version}`).join(" and ");
  const title = derived ? "DAB Render Sans Thai and DAB Render Mono" : fonts.map((f) => f.family).join(" and ");
  const note = derived ? [
    wrap(`The *.typeface.json files in this folder are Modified Versions, under the SIL Open Font License 1.1, of ${fonts.map((f) => f.family).join(" and ")}: scripts/woff2_to_typeface.py converted the glyph outlines of the fonts in frontend/public/fonts into three.js typeface JSON. They are used only to render the hero background video of DAB's landing page.`),
    wrap('Because they are modified, they do not use the Reserved Font Name "Plex" (condition 3 of the licence below):'),
    derived.map((d) => `  ${d.file.padEnd(Math.max(...derived.map((x) => x.file.length)))}  ${d.family}`).join("\n"),
    wrap(`IBM Corp. is named below only as the copyright holder of the original fonts (condition 4); IBM has not reviewed or endorsed these versions. The copyright notices and the licence are copied from the LICENSE files of the npm packages the original fonts come from: ${sources}.`),
  ] : [
    wrap(`Data Analysis Bot (DAB) uses these two font families without modifying them. The app bundles them from the npm packages ${sources}, and the landing and legal pages serve copies of the same font files. The copyright notices and the licence below are copied from those packages' LICENSE files.`),
    wrap(`IBM's own release of IBM Plex names "Plex" as a Reserved Font Name. The 3D lettering in the hero video on DAB's landing page was rendered from outlines converted from these fonts; because those outlines are modified, they are named "DAB Render Sans Thai" and "DAB Render Mono" instead.`),
  ];
  const heading = `${title} - SIL Open Font License, Version 1.1`;
  const notices = fonts.map((f) => `${f.family} (${f.pkgName} ${f.version}):\n${f.copyright}`);
  return `${[`${heading}\n${"=".repeat(heading.length)}`, ...note, "-".repeat(78), ...notices, fonts[0].body].join("\n\n")}\n`;
}
